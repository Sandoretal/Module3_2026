"""Build docs/notebook-index.js: the section headings of every rendered student
notebook, with links to them, for the site-wide search (docs/search.html).

Only the notebooks listed in render_site_notebooks.NOTEBOOKS are indexed, so the
solution notebooks never appear in search results. render_site_notebooks.py runs
this automatically after rendering; it can also be run on its own:

    python tools/build_search_index.py
"""

import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
RENDERED = DOCS / "rendered-notebooks"
OUT = DOCS / "notebook-index.js"

HEADING = re.compile(r"<h([1-4]) id=\"([^\"]+)\"[^>]*>(.*?)</h\1>", re.S)

# Title-cell headings that every notebook repeats; they would only clutter results.
SKIP = re.compile(
    r"^(Real-world data coding|MSc in Translational|Department of Brain|Imperial College"
    r"|Contributors|Autumn 20\d\d|Learning outcomes|Supporting materials?|Setup)",
    re.I,
)


def notebook_list():
    from render_site_notebooks import NOTEBOOKS  # same folder

    return NOTEBOOKS


def clean(fragment):
    text = re.sub(r"<a class=\"anchor-link\".*?</a>", "", fragment, flags=re.S)
    text = re.sub(r"<[^>]+>", "", text)
    text = html.unescape(text).replace("¶", "")
    return re.sub(r"\s+", " ", text).strip(" :")


def main():
    entries = []
    for rel in notebook_list():
        page = RENDERED / Path(rel).with_suffix(".html")
        if not page.exists():
            print(f"skipped (not rendered yet): {rel}")
            continue
        tutorial = int(re.search(r"tutorial_(\d)", rel).group(1))
        notebook = Path(rel).stem
        url = page.relative_to(DOCS).as_posix()
        count = 0
        for level, anchor, inner in HEADING.findall(page.read_text(encoding="utf-8")):
            title = clean(inner)
            if not title or SKIP.match(title):
                continue
            entries.append({
                "title": title,
                "tutorial": tutorial,
                "notebook": notebook,
                "url": f"{url}#{anchor}",
                "level": int(level),
            })
            count += 1
        print(f"{rel}: {count} headings")

    OUT.write_text(
        "// Generated by tools/build_search_index.py. Do not edit by hand.\n"
        "window.MODULE3_NOTEBOOK_INDEX = "
        + json.dumps(entries, ensure_ascii=False, indent=1)
        + ";\n",
        encoding="utf-8",
    )
    print(f"wrote {len(entries)} headings to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
